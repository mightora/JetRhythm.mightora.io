/* Build a self-contained direct-API deployment when Wrangler auth is unavailable.
 * Wrangler static assets (configured in wrangler.jsonc) remain the preferred route.
 */
const fs = require('node:fs');
const path = require('node:path');
const {gzipSync} = require('node:zlib');
const base = path.resolve(__dirname,'..');
const dist = path.join(base,'dist');
const mime = {
  '.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8',
  '.css':'text/css; charset=utf-8','.svg':'image/svg+xml','.png':'image/png',
  '.xml':'application/xml; charset=utf-8','.txt':'text/plain; charset=utf-8',
  '.json':'application/json; charset=utf-8','.webmanifest':'application/manifest+json',
  '.yaml':'text/yaml; charset=utf-8','.zip':'application/zip'
};
function entries(folder) {
  return fs.readdirSync(folder,{withFileTypes:true}).flatMap(item => {
    const file = path.join(folder,item.name);
    if (item.isDirectory()) return entries(file);
    if (item.name === '.nojekyll' || item.name === 'CNAME') return [];
    const webPath = '/' + path.relative(dist,file).split(path.sep).join('/');
    return [[webPath,[mime[path.extname(file)] || 'application/octet-stream',gzipSync(fs.readFileSync(file),{level:9}).toString('base64')]]];
  });
}
const assets = Object.fromEntries(entries(dist));
const source = fs.readFileSync(path.join(base,'worker/index.mjs'),'utf8');
const embedded = `\n/* Generated by scripts/bundle-worker.cjs; source of truth is dist/. */\n` +
  `const STATIC_FILES=${JSON.stringify(assets)};\n` +
  `function embeddedAsset(request){const u=new URL(request.url);const item=STATIC_FILES[u.pathname==='/'?'/index.html':u.pathname];`+
  `if(!item)return new Response('Not found',{status:404,headers:{'content-type':'text/plain'}});`+
  `const headers={'content-type':item[0],'x-content-type-options':'nosniff','cache-control':'public, max-age=300'};`+
  `if(request.method==='HEAD')return new Response(null,{headers});`+
  `const bytes=Uint8Array.from(atob(item[1]),c=>c.charCodeAt(0));`+
  `const body=new Blob([bytes]).stream().pipeThrough(new DecompressionStream('gzip'));`+
  `return new Response(body,{headers});}\n`;
const target = path.join(base,'worker/deploy.mjs');
fs.writeFileSync(target,source+'\n'+embedded);
console.log('Bundled',Object.keys(assets).length,'static files in',target,'(',fs.statSync(target).size,'bytes)');
