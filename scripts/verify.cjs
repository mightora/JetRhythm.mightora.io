const fs=require('node:fs');
const assert=require('node:assert/strict');
const path=require('node:path');
const dist=path.resolve(__dirname,'../dist');
const read=p=>fs.readFileSync(path.join(dist,p),'utf8');
for(const required of ['index.html','styles.css','core.js','airports.js','app.js','robots.txt','sitemap.xml','favicon.svg','privacy.html','network.html','METHODOLOGY.html','downloads/JetRhythm-Offline.html','downloads/JetRhythm-Offline.zip'])assert.ok(fs.existsSync(path.join(dist,required)),required+' missing');
const html=read('index.html');
assert.match(html,/<title>JetRhythm.*Jet Lag Calculator/);
assert.match(html,/"@type":"WebApplication"/);
assert.match(html,/"@type":"FAQPage"/);
assert.match(html,/rel="canonical"/);
assert.match(html,/mightora-header/);
assert.match(html,/mightora-author/);
assert.match(html,/mightora-footer/);
assert.match(html,/id="flight-legs"/);
assert.match(html,/id="results"/);
assert.match(html,/id="rhythm-chart"/);
assert.match(html,/src="airports.js"/);
assert.doesNotMatch(read('app.js'),/class="from-zone"|class="to-zone"/);
assert.match(read('app.js'),/lookupFlight/);
assert.match(html,/<meta name="flight-lookup-url" content="\/api\/flights">/);
assert.match(read('styles.css'),/\.gantt-scroller/);
assert.ok((read('airports.js').match(/"[A-Z]{3}":\[/g)||[]).length > 7000,'full airport data required');
assert.match(read('styles.css'),/\.quick-jump-nav\s*\{[^}]*position:\s*sticky/);
const offline=read('downloads/JetRhythm-Offline.html');
assert.match(offline,/<meta name="flight-lookup-url" content="">/);
assert.match(offline,/Offline Edition – No Internet Connection Required/);
assert.match(offline,/data:image\/png;base64,/);
assert.match(offline,/<script>\s*\/\* JetRhythm/);
assert.match(offline,/window\.JetRhythmAirports\s*=/);
assert.doesNotMatch(offline,/<script[^>]+src=/);
assert.doesNotMatch(offline,/<link[^>]+rel="stylesheet"[^>]+href="https:/);
assert.doesNotMatch(offline,/<img[^>]+src="https:/);
assert.doesNotMatch(offline,/fetch\s*\(\s*['"]https?:\/\//);
const archive=fs.readFileSync(path.join(dist,'downloads/JetRhythm-Offline.zip'));
assert.equal(archive.readUInt32LE(0),0x04034b50);
for(const file of ['JetRhythm-Offline.html','README.txt','LICENSE','THIRD_PARTY_NOTICES.md'])assert.ok(archive.includes(Buffer.from(file)),file+' missing in ZIP');
console.log('Verified SEO, branding, offline independence, sitemap, downloads, ZIP and static output.');
